function titleCase(value: string) {
  return value
    .split(/[\s-]+/)
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1).toLowerCase())
    .join(" ");
}

export function toEnglishSurname(raw: string) {
  const value = raw.trim();
  if (!value) return "";
  if (/^[A-Za-z][A-Za-z\s'-]*$/.test(value)) return titleCase(value);
  if (compoundSurnames[value]) return compoundSurnames[value];
  const compound = value.slice(0, 2);
  if (compoundSurnames[compound]) return compoundSurnames[compound];
  return surnames[value.charAt(0)] ?? "";
}
